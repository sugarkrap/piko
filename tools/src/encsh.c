static unsigned char decode_table[256];
static int decode_table_ready = 0;

static void build_decode_table(void)
{
    int i;
    for (i = 0; i < 256; i++)
        decode_table[enctab[i]] = (unsigned char)i;
    decode_table_ready = 1;
}

static unsigned char decode_c(unsigned char c)
{
    if (!decode_table_ready) build_decode_table();
    return decode_table[c];
}

static unsigned char encode_c(unsigned char c)
{
    return enctab[c];
}

int main(int argc, char *argv[])
{
    int decode;
    int c;
    FILE *inf, *outf;

    if (argc < 4 || (strcmp(argv[1], "-e") != 0 && strcmp(argv[1], "-d") != 0)) {
        fprintf(stderr,
            "Encode file:\n\tencsh -e infile outfile\n"
            "Decode file:\n\tencsh -d infile outfile\n");
        return 1;
    }

    decode = (strcmp(argv[1], "-d") == 0);

    inf = fopen(argv[2], "rb");
    if (!inf) { perror(argv[2]); return 1; }
    outf = fopen(argv[3], "wb");
    if (!outf) { perror(argv[3]); fclose(inf); return 1; }

    while ((c = fgetc(inf)) != EOF)
        fputc(decode ? decode_c((unsigned char)c) : encode_c((unsigned char)c), outf);

    fclose(inf);
    fclose(outf);
    return 0;
}
